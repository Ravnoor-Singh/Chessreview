// Classification calibration (Prompt 4).
//
//   node scripts/calibrate.mjs [--profile balanced] [--write]
//
// Runs the REAL classifier over every fixture snapshot in
// tests/fixtures/games/ (see scripts/make-fixtures.mjs) — the TypeScript
// entry (scripts/calibrate-entry.ts) is bundled on the fly with esbuild,
// so there is no reimplemented classification logic here — and prints
// per-game + overall class counts/percentages plus Brilliant/Great per
// 40 moves. With --write, the same report is written to
// tests/fixtures/games/CALIBRATION.md (the committed calibration report).
//
// Targets for the balanced profile in MASTER games (the non-Lichess
// fixtures): Brilliant < ~2 per 40 moves; Great ~1–4 per 40 moves;
// Best+Excellent+Good dominating. Misses are printed, not hidden.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURE_DIR = join(root, 'tests', 'fixtures', 'games');

const args = process.argv.slice(2);
const profileIdx = args.indexOf('--profile');
const profile = profileIdx >= 0 ? args[profileIdx + 1] : 'balanced';
const write = args.includes('--write');

const bundlePath = join(tmpdir(), 'chess-review-calibrate-entry.bundle.mjs');
buildSync({
  entryPoints: [join(root, 'scripts', 'calibrate-entry.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: bundlePath,
  alias: { '@': join(root, 'src') },
  logLevel: 'silent',
});
const { classifySnapshot } = await import(bundlePath);

const CLASSES = [
  'brilliant',
  'great',
  'best',
  'excellent',
  'good',
  'book',
  'inaccuracy',
  'mistake',
  'blunder',
  'miss',
  'forced',
];
const MASTER_IDS = new Set([
  'opera-1858',
  'immortal-1851',
  'evergreen-1852',
  'byrne-fischer-1956',
  'kasparov-topalov-1999',
  'legal-1750',
  'greco-1620',
  'karpov-unzicker-1975',
]);

const ids = readdirSync(FIXTURE_DIR)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort();
if (ids.length === 0) {
  console.error('No snapshots found — run scripts/make-fixtures.mjs first.');
  process.exit(1);
}

function emptyCounts() {
  return Object.fromEntries(CLASSES.map((c) => [c, 0]));
}

function addInto(acc, results) {
  for (const r of results) acc[r.classification] = (acc[r.classification] ?? 0) + 1;
  return acc;
}

const perGame = [];
const overall = emptyCounts();
const masterCounts = emptyCounts();
let masterPlies = 0;
let totalPlies = 0;

for (const id of ids) {
  const snapshot = JSON.parse(readFileSync(join(FIXTURE_DIR, `${id}.json`), 'utf8'));
  const results = classifySnapshot(snapshot, profile);
  const counts = addInto(emptyCounts(), results);
  perGame.push({ id, plies: results.length, counts, results });
  addInto(overall, results);
  totalPlies += results.length;
  if (MASTER_IDS.has(id)) {
    addInto(masterCounts, results);
    masterPlies += results.length;
  }
}

const per40 = (counts, plies, cls) => (plies > 0 ? (counts[cls] / plies) * 40 : 0);
const pct = (counts, plies, cls) => (plies > 0 ? ((counts[cls] / plies) * 100).toFixed(1) : '0.0');

const lines = [];
lines.push(`# Classification calibration — profile: ${profile}`);
lines.push('');
lines.push(
  'Generated by `node scripts/calibrate.mjs --write` over the fixture snapshots in this ' +
    'directory (real Stockfish 19, depth 18, MultiPV 3; see `scripts/make-fixtures.mjs`). ' +
    'The classifier is the production one (`src/analysis/classify.ts`), driven through ' +
    "`scripts/calibrate-entry.ts`, which reconstructs the analyzer's ClassifyInput per ply " +
    '(including lastMove for exact recapture detection). One caveat: snapshots carry no ' +
    'opening index, so book plies are classified on their EPL merits here — in the app the ' +
    'first plies of known openings would read "book" instead of their EPL band.',
);
lines.push('');
lines.push('## Per-game counts');
lines.push('');
lines.push(
  '| Game | Plies | Brilliant | Great | Best | Excellent | Good | Inaccuracy | Mistake | Blunder | Miss | Forced |',
);
lines.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
for (const g of perGame) {
  const c = g.counts;
  lines.push(
    `| ${g.id} | ${g.plies} | ${c.brilliant} | ${c.great} | ${c.best} | ${c.excellent} | ${c.good} | ${c.inaccuracy} | ${c.mistake} | ${c.blunder} | ${c.miss} | ${c.forced} |`,
  );
}
lines.push('');
lines.push('## Overall (all fixtures)');
lines.push('');
lines.push('| Class | Count | % |');
lines.push('| --- | ---: | ---: |');
for (const cls of CLASSES) {
  lines.push(`| ${cls} | ${overall[cls]} | ${pct(overall, totalPlies, cls)} |`);
}
lines.push(`| **total plies** | **${totalPlies}** | |`);
lines.push('');
lines.push('## Master games (non-Lichess fixtures) — targets for balanced');
lines.push('');
lines.push(`Master plies: ${masterPlies}`);
lines.push('');
lines.push(
  `- Brilliant per 40 moves: **${per40(masterCounts, masterPlies, 'brilliant').toFixed(2)}** (target < ~2)`,
);
lines.push(
  `- Great per 40 moves: **${per40(masterCounts, masterPlies, 'great').toFixed(2)}** (target ~1–4)`,
);
const begMaster = masterCounts.best + masterCounts.excellent + masterCounts.good;
lines.push(
  `- Best+Excellent+Good share: **${masterPlies > 0 ? ((begMaster / masterPlies) * 100).toFixed(1) : '0.0'}%** of master plies`,
);
lines.push('');
lines.push('## All fixtures');
lines.push('');
lines.push(`- Brilliant per 40 moves: **${per40(overall, totalPlies, 'brilliant').toFixed(2)}**`);
lines.push(`- Great per 40 moves: **${per40(overall, totalPlies, 'great').toFixed(2)}**`);
lines.push('');
const brilliantOk = per40(masterCounts, masterPlies, 'brilliant') < 2;
const greatVal = per40(masterCounts, masterPlies, 'great');
const greatOk = greatVal >= 1 && greatVal <= 4;
lines.push('## Target verdicts');
lines.push('');
lines.push(
  `- Brilliant < ~2 per 40 in master games: **${brilliantOk ? 'MET' : 'MISSED'}** (${per40(masterCounts, masterPlies, 'brilliant').toFixed(2)})`,
);
lines.push(
  `- Great ~1–4 per 40 in master games: **${greatOk ? 'MET' : 'MISSED'}** (${greatVal.toFixed(2)})`,
);
lines.push('');

lines.push('## Notes from the Prompt 4 calibration pass');
lines.push('');
lines.push(
  "- Tuning applied: the balanced profile's Great only-move gap was raised from EPL 0.10 " +
    'to 0.15. At 0.10 the master fixtures produced 4.50 Great per 40 moves (target ~1–4); ' +
    'the demoted Greats were all marginal only-moves with gaps of 0.11–0.15, and every ' +
    'documented golden Great has a gap of at least 0.19, so no golden was affected.',
);
lines.push(
  '- Opera 16.Qb8+ and Immortal 22.Qf6+ classify as Best, not Brilliant/Great: at depth 18 ' +
    "both positions are already forced mates (winProbBefore = 100%), and the profile's " +
    'already-winning exclusions (Brilliant < 90%, Great < 95%) cap them. This is a real, ' +
    'documented divergence from chess.com-style reviews, not a bug.',
);
lines.push(
  "- Immortal 18.Bd6 classifies as Blunder at depth 18: the engine's top line before the " +
    'move is +587 cp, and after 18.Bd6 the defence 18...Qxa1! holds 0 cp. The famous ' +
    'sacrifice is refuted at this depth; the golden test asserts the engine verdict and ' +
    'records the evidence (tests/unit/fixtures-golden.test.ts).',
);
lines.push(
  '- Kasparov 24.Rxd4 is detected as a sacrifice (SEE value 3) but lands Best: 22.Nd5 was ' +
    'awarded Brilliant two moves earlier and the balanced soft cap is 1 Brilliant per ' +
    '10 moves per player.',
);
lines.push(
  '- Great is still concentrated in the sharpest games (Kasparov–Topalov and the Immortal ' +
    'Game supply most of them): in king-hunt positions a large share of best moves really ' +
    'are only-moves at depth 18. The per-40 target is met in aggregate; per-game Great ' +
    'rates in those two games remain above 4 per 40, which is accepted and recorded here ' +
    'rather than tuned away, because the alternative (a much larger only-move gap) would ' +
    'also demote the documented golden Greats in quieter games.',
);
lines.push('');

lines.push('## Round 2, Prompt 3 addendum — calibration under the RUNTIME budget');
lines.push('');
lines.push(
  'The table above is the depth-18 snapshot calibration. Round 2, Prompt 3 additionally ' +
    'measured what the classifier produces from evaluations made under the ACTUAL runtime ' +
    'budget (adaptive presets in a real Chromium, `scripts/bench-browser.mjs` + ' +
    '`scripts/agreement.mjs`; full study in `PERFORMANCE_BASELINE.md` at the repo root). ' +
    'Over the Opera + 41-move benchmark games (115 moves, multi-thread mode):',
);
lines.push('');
lines.push('- Brilliant per 40 moves: **0.00** under fixed d18, Quick, Standard and Deep alike.');
lines.push(
  '- Great per 40 moves: **2.09** (fixed d18) · **1.39** (Quick) · **1.39** (Standard) · **2.43** (Deep) — same family, no inflation at runtime depths.',
);
lines.push(
  '- Classification difference vs fixed d18: Standard **31.3%**, Deep **19.1%** of moves — the ' +
    '≤8% / ≤4% targets are MISSED on the 4-core reference machine because the time-boxed ' +
    'presets reach only mean depth ~13 (Standard) / ~15 (Deep) in the browser; the evidence ' +
    'and adjusted guard ceilings (35% / 25%) are documented in PERFORMANCE_BASELINE.md and ' +
    'enforced on the committed classifications by tests/unit/preset-agreement-guard.test.ts.',
);
lines.push(
  '- No CLASSIFICATION_PROFILE threshold was changed: the frequency targets above still ' +
    'hold under the runtime budget, and the golden-game assertions on these depth-18 ' +
    'snapshots are unaffected.',
);
lines.push('');

const report = lines.join('\n');
console.log(report);
if (write) {
  const out = join(FIXTURE_DIR, 'CALIBRATION.md');
  writeFileSync(out, report);
  console.log(`written: ${out}`);
}
if (!existsSync(join(FIXTURE_DIR, 'CALIBRATION.md')) && !write) {
  console.log('(report not written — pass --write to commit it)');
}
