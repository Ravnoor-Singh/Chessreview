const BY_ID = new Map(PIECE_SET_DEFS.map((d) => [d.id, d]));

export function isPieceSetId(value: unknown): value is PieceSetId {
  return typeof value === 'string' && BY_ID.has(value);
}

/** Unknown / legacy stored values fall back to the Classic (cburnett) set. */
export function normalizePieceSetId(value: unknown): string {
  return typeof value === 'string' && BY_ID.has(value) ? value : 'cburnett';
}

export function getPieceSetDef(id: string | undefined): PieceSetDef | undefined {
  return id ? BY_ID.get(id) : undefined;
}

/** Public URL of one piece image, e.g. pieceSrcFor('neo', 'bQ') → '/pieces/neo/bQ.svg'. */
export function pieceSrcFor(set: string, pieceKey: string): string {
  return `/pieces/${set}/${pieceKey}.svg`;
}
