// Generate public/sw.js from src/lib/swCore.mjs + the SW event handlers.
//
// Why hand-rolled (Prompt 9 decision): the app has exactly four caching
// routes (precache, runtime cache-first, engine cache-first, network-only
// API) and one hard requirement — COOP/COEP header injection on every
// SW-served response. Serwist/Workbox would add a build plugin, a runtime
// dependency surface and a config layer to reimplement those ~120 lines,
// and would still need the custom header injection. The pure logic lives
// in src/lib/swCore.mjs (unit-tested); this script inlines it verbatim so
// the shipped worker runs the tested code — no duplication.
//
// public/sw.js is committed AND regenerated by `npm run build`, so a stale
// copy can never ship: edit swCore.mjs or the handlers below, never sw.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const coreSource = readFileSync(join(root, 'src/lib/swCore.mjs'), 'utf8');
// The SW is a classic script: strip the ESM `export` keywords, keep the code.
let core = coreSource.replace(/^export (?=(?:const|let|var|function|class) )/gm, '');

// Prompt 7 version-mismatch guard: stamp the engine payload's content
// fingerprint into the generated worker (see ENGINE_FINGERPRINT in
// swCore.mjs). Derived from public/engine/engine-manifest.json — version
// plus every file's name/size/SHA-256 — so any engine payload change
// changes sw.js (triggering the SW update flow) and the engine cache
// name (orphaning stale engine bytes). Absent manifest → 'nomanifest'.
{
  const { createHash } = await import('node:crypto');
  let fingerprint = 'nomanifest';
  try {
    const manifest = JSON.parse(
      readFileSync(join(root, 'public', 'engine', 'engine-manifest.json'), 'utf8'),
    );
    const input = `${manifest.version}|${manifest.files
      .map((f) => `${f.name}:${f.size}:${f.sha256}`)
      .sort()
      .join('|')}`;
    fingerprint = createHash('sha256').update(input).digest('hex').slice(0, 16);
  } catch {
    // No engine manifest (e.g. a bare checkout): the placeholder stands.
  }
  if (!/const ENGINE_FINGERPRINT = '[^']*';/.test(core)) {
    throw new Error('build-sw: ENGINE_FINGERPRINT literal not found in swCore.mjs.');
  }
  core = core.replace(
    /const ENGINE_FINGERPRINT = '[^']*';/,
    `const ENGINE_FINGERPRINT = '${fingerprint}';`,
  );
  // Prompt 2: stamp the manifest's file list the same way, so the
  // activation purge (engineEntriesToPurge in swCore.mjs) knows exactly
  // which entries the CURRENT engine cache may hold. Absent manifest →
  // the empty placeholder stands and the purge is a no-op by design.
  let fileNames = [];
  try {
    const manifest = JSON.parse(
      readFileSync(join(root, 'public', 'engine', 'engine-manifest.json'), 'utf8'),
    );
    fileNames = manifest.files.map((f) => String(f.name)).sort();
  } catch {
    // No engine manifest: the placeholder stands.
  }
  if (!/const ENGINE_FILE_NAMES = \[[^\]]*\];/.test(core)) {
    throw new Error('build-sw: ENGINE_FILE_NAMES literal not found in swCore.mjs.');
  }
  core = core.replace(
    /const ENGINE_FILE_NAMES = \[[^\]]*\];/,
    `const ENGINE_FILE_NAMES = ${JSON.stringify(fileNames)};`,
  );
}
if (core.includes('\nexport ') || core.startsWith('export ')) {
  throw new Error('build-sw: un-stripped export left in swCore.mjs — check its export style.');
}
if (/^import /m.test(core)) {
  throw new Error('build-sw: swCore.mjs must stay import-free to be inlined into sw.js.');
}

const handlers = `
// ---------------------------------------------------------------------------
// Event handlers (generated together with the core above — see
// scripts/build-sw.mjs). Plain classic-worker code; the pure decisions
// (classification, cache names, header injection) come from swCore.
// ---------------------------------------------------------------------------

var PRECACHE_URLS = precacheUrls();

async function precacheBuildAssets() {
  // Hashed chunk names change every build, so they cannot be listed in
  // swCore. Instead, discover the CURRENT build's assets from the served
  // documents themselves: every /_next/static/* URL referenced by / and
  // /review, plus url() assets (the self-hosted fonts) inside their CSS.
  // Anything still missed (lazily loaded chunks) is runtime-cached on
  // first use — see the README's one-visit caveat.
  var runtime = await caches.open(RUNTIME_CACHE);
  var assets = new Set();
  var cssAssets = [];
  for (var doc of ['/', '/review']) {
    try {
      var res = await fetch(doc);
      if (!res.ok) continue;
      var html = await res.text();
      var re = new RegExp('(?:src|href)="(/_next/static/[^"]+)"', 'g');
      var m;
      while ((m = re.exec(html)) !== null) {
        assets.add(m[1]);
        if (m[1].endsWith('.css')) cssAssets.push(m[1]);
      }
    } catch (err) {
      // Document unreachable — runtime caching will cover it later.
    }
  }
  for (var css of cssAssets) {
    try {
      var cssRes = await fetch(css);
      if (!cssRes.ok) continue;
      var cssText = await cssRes.text();
      var urlRe = new RegExp('url\\((/?_next/static/[^)]+)\\)', 'g');
      var um;
      while ((um = urlRe.exec(cssText)) !== null) {
        assets.add(um[1].startsWith('/') ? um[1] : '/' + um[1]);
      }
    } catch (err) {
      // Non-fatal.
    }
  }
  await Promise.all(
    Array.from(assets).map(async function (url) {
      try {
        await runtime.add(url);
      } catch (err) {
        // Non-fatal: runtime cache-first populates on first real request.
      }
    }),
  );
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    (async function () {
      var cache = await caches.open(APP_CACHE);
      // Add one by one: a single 404 must not fail the whole install.
      await Promise.all(
        PRECACHE_URLS.map(async function (url) {
          try {
            await cache.add(url);
          } catch (err) {
            // Optional asset missing — the runtime cache will fill it later.
          }
        }),
      );
      await precacheBuildAssets();
    })(),
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    (async function () {
      var names = await caches.keys();
      await Promise.all(cachesToDelete(names).map(function (name) { return caches.delete(name); }));
      // Prompt 2 entry-level purge: whole-cache deletion above cannot
      // catch stale payload entries that live INSIDE the current engine
      // cache (e.g. a file a previous payload shipped under a cache name
      // that did not change). Delete every entry the current manifest
      // does not list; the pure decision is engineEntriesToPurge in
      // swCore.mjs (unit-tested), fed by the build-stamped
      // ENGINE_FILE_NAMES. A failure here must never block activation.
      try {
        if (ENGINE_FILE_NAMES && ENGINE_FILE_NAMES.length) {
          var engineCache = await caches.open(engineSwCurrentCacheName());
          var requests = await engineCache.keys();
          var urls = requests.map(function (r) { return r.url; });
          await Promise.all(
            engineEntriesToPurge(urls, ENGINE_FILE_NAMES).map(function (url) {
              return engineCache.delete(url);
            }),
          );
        }
      } catch (err) {
        // Non-fatal: stale entries are at worst re-validated by the
        // loader's SHA-256 check before any engine byte runs.
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', function (event) {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

async function putInCache(cacheName, request, response) {
  try {
    var cache = await caches.open(cacheName);
    await cache.put(request, response);
  } catch (err) {
    // Quota or opaque-response failures are non-fatal: the network copy works.
  }
}

async function cacheFirst(request, cacheName, searchAllCaches) {
  var hit = searchAllCaches ? await caches.match(request) : undefined;
  if (!hit) {
    var own = await caches.open(cacheName);
    hit = await own.match(request);
  }
  if (hit) return injectIsolationHeaders(hit);
  var response = await fetch(request);
  if (response && response.ok) putInCache(cacheName, request, response.clone());
  return injectIsolationHeaders(response);
}

async function networkFirstEngineManifest(request) {
  // Prompt 2: the manifest is network-first — a cache-first manifest
  // would pin the old engine's hashes forever, defeating both the
  // no-cache response header and the fingerprint-keyed cache name. The
  // cached copy (kept in the current engine cache) is only the offline
  // fallback.
  var cacheName = engineSwCurrentCacheName();
  try {
    var response = await fetch(request);
    if (response && response.ok) putInCache(cacheName, request, response.clone());
    return injectIsolationHeaders(response);
  } catch (err) {
    var cache = await caches.open(cacheName);
    var hit = await cache.match(request);
    if (hit) return injectIsolationHeaders(hit);
    throw err;
  }
}

async function networkFirstNavigation(request) {
  try {
    var response = await fetch(request);
    if (response && response.ok) putInCache(APP_CACHE, request, response.clone());
    return injectIsolationHeaders(response);
  } catch (err) {
    var hit = await caches.match(request);
    if (hit) return injectIsolationHeaders(hit);
    var shell = await caches.match('/');
    if (shell) return injectIsolationHeaders(shell);
    throw err;
  }
}

self.addEventListener('fetch', function (event) {
  var request = event.request;
  var kind = classifyRequest(request.url, {
    method: request.method,
    mode: request.mode,
    origin: self.location.origin,
  });
  if (kind === 'network-only' || kind === 'passthrough') return; // browser default (network)
  if (kind === 'engine-manifest') {
    event.respondWith(networkFirstEngineManifest(request));
  } else if (kind === 'engine') {
    event.respondWith(cacheFirst(request, engineSwCurrentCacheName(), false));
  } else if (kind === 'static') {
    event.respondWith(cacheFirst(request, RUNTIME_CACHE, false));
  } else if (kind === 'navigation') {
    event.respondWith(networkFirstNavigation(request));
  } else {
    // runtime: pieces/openings/sounds/icons/manifest are precached, so a
    // hit in ANY cache wins; otherwise network + populate the runtime cache.
    event.respondWith(cacheFirst(request, RUNTIME_CACHE, true));
  }
});
`;

const banner =
  '// GENERATED by scripts/build-sw.mjs from src/lib/swCore.mjs — DO NOT EDIT.\n' +
  '// Regenerate with `npm run build:sw` (also runs as part of `npm run build`).\n' +
  '//\n' +
  '// CRITICAL: responses served by a service worker do NOT inherit the\n' +
  '// server COOP/COEP headers (next.config.js / vercel.json / _headers).\n' +
  '// Every response below is passed through injectIsolationHeaders() so the\n' +
  '// page stays crossOriginIsolated and the multi-threaded Stockfish build\n' +
  '// keeps working after SW activation.\n\n';

const output = banner + core + handlers;
// A syntactically broken SW fails registration silently in the browser —
// never let one be written.
try {
  new Function(output);
} catch (err) {
  throw new Error('build-sw: generated sw.js does not parse: ' + err.message);
}
writeFileSync(join(root, 'public/sw.js'), output);
console.log('build-sw: wrote public/sw.js (' + output.length + ' bytes)');
