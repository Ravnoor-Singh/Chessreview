#!/usr/bin/env node
/**
 * Repository hygiene check (Post-Round-2, Prompt 5): fails when
 *  (a) any tracked file is a `*.log` file (generated logs are gitignored
 *      and must never be committed), or
 *  (b) a tracked text file matches a conservative likely-secret pattern
 *      (cloud / VCS / API token shapes, private-key blocks, literal
 *      password assignments).
 *
 * Personal absolute paths (`/home/<user>/…`, `/Users/<user>/…`,
 * `C:\Users\<user>\…`) are also scanned and reported as WARNINGS: they
 * are not secrets, but they leak a contributor's local layout and usually
 * mark a hard-coded fallback that should be an environment variable.
 * Pass `--strict` to make warnings fail the check as well.
 *
 * File list: `git ls-files` when git is available; otherwise a
 * filesystem walk excluding generated / vendored directories
 * (node_modules, .next*, coverage, public/engine, …). Binary files and
 * files over 2 MiB are skipped. This script excludes itself: its own
 * source necessarily contains the pattern literals it searches for.
 * Findings print the pattern name and location only, never the matched
 * secret value.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SELF = relative(ROOT, fileURLToPath(import.meta.url))
  .split('\\')
  .join('/');
const STRICT = process.argv.includes('--strict');
const MAX_BYTES = 2 * 1024 * 1024;

const WALK_EXCLUDES = new Set([
  '.git',
  'node_modules',
  '.next',
  '.next-noiso',
  '.next-cdn',
  '.next-lite',
  'out',
  'dist',
  'coverage',
  '.lighthouseci',
  'test-results',
  'playwright-report',
]);

const BINARY_EXTENSIONS = new Set([
  '.png',
  '.jpg',
  '.jpeg',
  '.gif',
  '.webp',
  '.ico',
  '.wasm',
  '.woff',
  '.woff2',
  '.ttf',
  '.otf',
  '.pdf',
  '.zip',
  '.gz',
  '.mp3',
  '.wav',
  '.mp4',
]);

// Conservative shapes only: a match should be a real credential, not a
// variable name, a documented placeholder, or a test fixture label.
const SECRET_PATTERNS = [
  ['aws-access-key-id', /\bAKIA[0-9A-Z]{16}\b/],
  ['github-token', /\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36,}\b/],
  ['github-fine-grained-pat', /\bgithub_pat_[A-Za-z0-9_]{22,}\b/],
  ['openai-style-key', /\bsk-(?:proj-)?[A-Za-z0-9_-]{20,}\b/],
  ['google-api-key', /\bAIza[0-9A-Za-z_-]{35}\b/],
  ['slack-token', /\bxox[baprs]-[A-Za-z0-9-]{10,}\b/],
  ['private-key-block', /-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP )?PRIVATE KEY-----/],
  ['password-assignment', /\b(?:password|passwd)\s*[:=]\s*["'][^"'\s]{8,}["']/i],
];

const PERSONAL_PATH_PATTERNS = [
  ['unix-home-path', /\/(?:home|Users)\/[A-Za-z0-9._-]+\//],
  ['windows-user-path', /\b[A-Za-z]:\\Users\\[A-Za-z0-9._-]+\\/],
];

function listFilesViaGit() {
  try {
    const out = execFileSync('git', ['ls-files'], { cwd: ROOT, encoding: 'utf8' });
    const files = out.split('\n').filter(Boolean);
    return files.length > 0 ? files : null;
  } catch {
    return null;
  }
}

function listFilesViaWalk() {
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (WALK_EXCLUDES.has(entry.name)) continue;
        if (entry.name === 'engine' && relative(ROOT, dir).split('\\').join('/') === 'public') {
          continue; // public/engine — generated by postinstall
        }
        walk(join(dir, entry.name));
      } else if (entry.isFile()) {
        files.push(relative(ROOT, join(dir, entry.name)).split('\\').join('/'));
      }
    }
  };
  walk(ROOT);
  return files;
}

const files = listFilesViaGit() ?? listFilesViaWalk();
const failures = [];
const warnings = [];
let scanned = 0;

for (const file of files) {
  if (file === SELF) continue;
  if (file.toLowerCase().endsWith('.log')) {
    failures.push(`log-file: ${file} — generated logs must not be tracked (see .gitignore)`);
    continue;
  }
  const dot = file.lastIndexOf('.');
  if (dot >= 0 && BINARY_EXTENSIONS.has(file.slice(dot).toLowerCase())) continue;
  let text;
  try {
    if (statSync(join(ROOT, file)).size > MAX_BYTES) continue;
    text = readFileSync(join(ROOT, file), 'utf8');
  } catch {
    continue; // listed but unreadable / gone — nothing to scan
  }
  if (text.includes('\0')) continue; // binary content
  scanned += 1;
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i += 1) {
    for (const [name, pattern] of SECRET_PATTERNS) {
      if (pattern.test(lines[i])) {
        failures.push(`secret (${name}): ${file}:${i + 1}`);
      }
    }
    for (const [name, pattern] of PERSONAL_PATH_PATTERNS) {
      const match = lines[i].match(pattern);
      if (match) {
        warnings.push(`personal-path (${name}): ${file}:${i + 1} — ${match[0]}…`);
      }
    }
  }
}

for (const warning of warnings) console.log(`WARNING ${warning}`);
for (const failure of failures) console.error(`FAIL ${failure}`);
console.log(
  `repo-hygiene: scanned ${scanned} text files (${files.length} listed), ` +
    `${failures.length} failure(s), ${warnings.length} warning(s)`,
);
if (failures.length > 0 || (STRICT && warnings.length > 0)) {
  process.exit(1);
}
console.log('repo-hygiene: OK');
